export function languageLabelForPath(filePath: string): string {
  const name = fileName(filePath).toLowerCase();
  if (name.endsWith(".cake")) return "Cake";
  if (name === "cake.config") return "Cake 配置";
  return LANGUAGE_LABELS[languageForPath(filePath)] || "文本";
}

export function isConfigPreviewPath(filePath: string): boolean {
  return /^(json|yaml|ini|xml)$/.test(languageForPath(filePath));
}

export function prettyConfigContent(filePath: string, content: string): string {
  if (languageForPath(filePath) !== "json") return content;
  try {
    return JSON.stringify(JSON.parse(content), null, 2);
  } catch {
    return content;
  }
}

export function highlightLanguageForPath(filePath: string): string {
  return HLJS_ALIASES[languageForPath(filePath)] || "";
}
