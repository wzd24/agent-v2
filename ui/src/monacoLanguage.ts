function fileName(filePath: string): string {
  return String(filePath || "").split(/[\\/]/).pop() || "";
}

export function languageForPath(filePath: string): string {
  const dotted = fileName(filePath).toLowerCase();
  if (!dotted) return "plaintext";
  if (FILENAME_LANGUAGES[dotted]) return FILENAME_LANGUAGES[dotted];
  if (dotted === ".env" || dotted.startsWith(".env.")) return "ini";
  if (/^dockerfile(?:\.[^.]+)*$/.test(dotted) || /^containerfile(?:\.[^.]+)*$/.test(dotted)) return "dockerfile";
  if (/^(?:docker-)?compose(?:\.[^.]+)*\.(?:ya?ml)$/.test(dotted)) return "yaml";
  if (/^(?:web|app|nuget|packages|runtime)(?:\.[^.]+)*\.config$/.test(dotted)) return "xml";
  if (/^appsettings(?:\.[^.]+)*\.json$/.test(dotted)) return "json";
  if (/^tsconfig(?:\.[^.]+)*\.json$/.test(dotted)) return "json";
  if (/^makefile(?:\.[^.]+)*$/.test(dotted) || /^gnumakefile(?:\.[^.]+)*$/.test(dotted)) return "ini";
  if (/\.cake$/.test(dotted) || dotted === "cake.config") return dotted === "cake.config" ? "ini" : "csharp";
  if (/^jenkinsfile(?:\.[^.]+)*$/.test(dotted)) return "java";
  if (/^(?:gulpfile|gruntfile)(?:\.[^.]+)*$/.test(dotted)) {
    const ext = dotted.includes(".") ? dotted.slice(dotted.lastIndexOf(".") + 1) : "";
    if (ext === "ts" || ext === "mts") return "typescript";
    if (ext === "coffee") return "coffee";
    return "javascript";
  }
  if (/^(?:webpack|rollup|vite|vitest|rspack|esbuild|farm|tsup|unbuild|electron-builder|forge)\.config(?:\.[^.]+)*$/.test(dotted)) {
    const ext = dotted.slice(dotted.lastIndexOf(".") + 1);
    if (ext === "ts" || ext === "mts" || ext === "cts") return "typescript";
    if (ext === "json" || ext === "jsonc") return "json";
    if (ext === "yml" || ext === "yaml") return "yaml";
    return "javascript";
  }
  if (/^taskfile(?:\.[^.]+)*\.(?:ya?ml)$/.test(dotted)) return "yaml";
  if (/^(?:azure-pipelines|\.gitlab-ci|\.travis|appveyor|\.appveyor|bitbucket-pipelines|\.drone|cloudbuild|buildspec|appspec|\.goreleaser|goreleaser|heroku|serverless)(?:\.[^.]+)*\.(?:ya?ml)$/.test(dotted)) return "yaml";
  if (/^pulumi(?:\.[^.]+)*\.(?:ya?ml)$/.test(dotted)) return "yaml";
  if (/^android\.(?:mk|bp)$/.test(dotted) || dotted === "application.mk") return dotted.endsWith(".bp") ? "python" : "ini";
  if (/^jamfile(?:\.[^.]+)*$/.test(dotted) || /^sconscript(?:\.[^.]+)*$/.test(dotted) || /^tiltfile(?:\.[^.]+)*$/.test(dotted)) {
    return dotted.startsWith("jamfile") ? "ini" : "python";
  }
  if (/\.sln$/.test(dotted)) return "ini";
  if (/\.slnx$/.test(dotted)) return "xml";
  if (/\.slnf$/.test(dotted)) return "json";
  if (/\.vdproj$/.test(dotted)) return "ini";
  if (/\.(?:cs|vb|fs|vcx|vc|njs|sql|py|wix|wap|android|sh|es|dc|cc|sf|pss|js|x|native|model|db|deploy|dt|rpt|dw)proj(?:\.(?:user|filters))?$/.test(dotted)) return "xml";
  if (/\.(?:proj|projitems|vcxitems|pubxml|publishproj)$/.test(dotted)) return "xml";
  for (const [suffix, language] of Object.entries(COMPOUND_EXTENSIONS)) {
    if (dotted === suffix || dotted.endsWith(`.${suffix}`)) return language;
  }
  const stem = dotted.includes(".") ? dotted.slice(0, dotted.lastIndexOf(".")) : dotted;
  if (STEM_FILENAMES[stem]) return STEM_FILENAMES[stem];
  const extension = dotted.includes(".") ? dotted.slice(dotted.lastIndexOf(".") + 1) : "";
  return EXTENSION_LANGUAGES[extension] || "plaintext";
}

